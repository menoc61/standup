typedef NotificationActionCallback = void Function(String action, int id);

/// Creates future alert instants using the same work-schedule rule as the
/// in-app action window. This is pure so queue filtering is testable without a
/// platform notification plugin.
@visibleForTesting
List<DateTime> reminderTimesForSchedule({
  required DateTime firstBoundary,
  required int frequencyMinutes,
  required int actionWindowMinutes,
  required WorkSchedule schedule,
  required DateTime now,
  String? quietHours,
  int count = 48,
  int maxLookAheadDays = 90,
  int dailyLimitMinutes = 0,
}) {
  if (frequencyMinutes <= 0) {
    throw ArgumentError.value(frequencyMinutes, 'frequencyMinutes');
  }
  if (actionWindowMinutes < 0 || count < 0 || maxLookAheadDays <= 0) {
    throw ArgumentError('Reminder queue bounds must be non-negative.');
  }

  final candidates = maxLookAheadDays * 24 * 60 ~/ frequencyMinutes;
  final reminders = <DateTime>[];
  var boundary = firstBoundary;
  for (var i = 0; i < candidates && reminders.length < count; i++) {
    final when = boundary.subtract(Duration(minutes: actionWindowMinutes));
    if (!when.isBefore(now.subtract(const Duration(minutes: 1))) &&
        schedule.allowsWindow(when, boundary) &&
        // The daily cut-off is evaluated per candidate, against *that* day's
        // boundary. Testing it once against `now` would queue a cut-off for
        // today and none for tomorrow, so after midnight the limit would
        // silently stop applying — the queue spans 90 days precisely because it
        // crosses days.
        !schedule.isPastDailyLimit(
          windowStart: when,
          limitMinutes: dailyLimitMinutes,
        ) &&
        !QuietHours.isQuietAt(quietHours, when)) {
      reminders.add(when);
    }
    boundary = StandWindow.nextBoundaryAfter(
      boundary: boundary,
      cadenceMinutes: frequencyMinutes,
    );
  }
  return reminders;
}

/// The instants a prelude notification should fire, one per queued reminder.
///
/// Pure, so the desktop warning schedule can be tested without a platform
/// notification plugin. A prelude is dropped when it would fire in the past (a
/// reminder scheduled less than [preludeMinutes] from now — a warning that
/// arrives *after* the break has started is worse than no warning), when it
/// falls inside quiet hours, or when it falls outside [schedule]. The in-app cue
/// applies the same quiet-hours rule, so the two never disagree about silence.
@visibleForTesting
List<DateTime> preludeTimesForReminders({
  required List<DateTime> reminders,
  required int preludeMinutes,
  required DateTime now,
  WorkSchedule? schedule,
  String? quietHours,
}) {
  if (preludeMinutes <= 0) return const [];
  final offset = Duration(minutes: preludeMinutes);
  final preludes = <DateTime>[];
  for (final reminder in reminders) {
    final prelude = reminder.subtract(offset);
    if (!prelude.isAfter(now)) continue;
    if (QuietHours.isQuietAt(quietHours, prelude)) continue;
    if (schedule != null && !schedule.allowsWindow(prelude, reminder)) {
      continue;
    }
    preludes.add(prelude);
  }
  return preludes;
}

class NotificationService {
  Future<void> _queueOperations = Future<void>.value();
  final FlutterLocalNotificationsPlugin _plugin =
      FlutterLocalNotificationsPlugin();
  final Map<int, Timer> _linuxTimers = {};
  bool _initialized = false;
  NotificationActionCallback? onActionReceived;
  String _languageCode = 'fr';

  /// The status-bar icon for every Android notification this service posts.
  ///
  /// Android tints this with the system foreground colour and keeps only the
  /// alpha channel, so it must be a white silhouette — hence
  /// `ic_notification`, generated by `scripts/icons/generate_icons.py` from the
  /// brand mark. Pointing it at the full-colour logo instead renders a
  /// featureless blob in the shade, which is what the app showed while no icon
  /// was set at all.
  ///
  /// Named rather than inlined because four call sites need it and a wrong
  /// name silently falls back to a blank glyph instead of throwing.
  static const String androidSmallIcon = 'ic_notification';

  /// The brand mark as the notification's large icon, in full colour.
  ///
  /// A dedicated 192px RGBA asset rather than the logo itself: the logo is an
  /// opaque 1024px image whose baked-in white background Android would draw as
  /// a block down the side of every notification, and re-decoding 415 KB on
  /// every post would put a multi-megabyte bitmap through the platform channel
  /// five times a minute for the ongoing countdown.
  ///
  /// Cached because the countdown re-posts on a timer.
  static AndroidBitmap<Uint8List>? _largeIcon;

  static Future<AndroidBitmap<Uint8List>?> _loadLargeIcon() async {
    if (_largeIcon != null) return _largeIcon;
    try {
      final data = await rootBundle.load(
        'assets/branding/notification_large.png',
      );
      // Honour the view's own offset and length. `buffer.asUint8List()` with no
      // arguments hands Android whatever else shares the backing store, which
      // silently corrupts the image rather than failing.
      _largeIcon = ByteArrayAndroidBitmap(
        data.buffer.asUint8List(data.offsetInBytes, data.lengthInBytes),
      );
    } catch (e) {
      // A missing large icon degrades to the small icon rather than dropping
      // the notification, so this is a warning and not a failure.
      debugPrint('Notification large icon unavailable: $e');
    }
    return _largeIcon;
  }

  /// Exposed so the ongoing-countdown notification reuses the same decoded
  /// bitmap instead of loading a second copy.
  static Future<AndroidBitmap<Uint8List>?> get notificationLargeIcon =>
      _loadLargeIcon();

  Future<void> initialize({
    NotificationActionCallback? onAction,
    String languageCode = 'fr',
  }) async {
    final previousLanguage = _languageCode;
    _languageCode = languageCode == 'en' ? 'en' : 'fr';
    if (_initialized && previousLanguage == _languageCode) return;
    if (onAction != null) onActionReceived = onAction;
    final french = _languageCode == 'fr';

    try {
      tz.initializeTimeZones();
    } catch (e) {
      debugPrint('Timezone initialization notice: $e');
    }

    const AndroidInitializationSettings androidSettings =
        AndroidInitializationSettings('@mipmap/ic_launcher');

    final DarwinInitializationSettings darwinSettings =
        DarwinInitializationSettings(
          // Ask from the onboarding/settings action after the user sees why
          // reminders are useful, never during app initialization.
          requestAlertPermission: false,
          requestBadgePermission: false,
          requestSoundPermission: false,
          notificationCategories: <DarwinNotificationCategory>[
            DarwinNotificationCategory(
              'standup_reminder',
              actions: <DarwinNotificationAction>[
                DarwinNotificationAction.plain(
                  'complete',
                  french ? 'Je me suis levé·e !' : 'I stood up!',
                ),
                DarwinNotificationAction.plain(
                  'snooze',
                  french ? 'Prochain rappel' : 'Next reminder',
                ),
                DarwinNotificationAction.plain(
                  'skip',
                  french ? 'Passer' : 'Skip',
                ),
              ],
            ),
          ],
        );

    const LinuxInitializationSettings linuxSettings =
        LinuxInitializationSettings(defaultActionName: 'Open StandUp');

    const WindowsInitializationSettings windowsSettings =
        WindowsInitializationSettings(
          appName: AppIdentity.windowsNotificationAppName,
          appUserModelId: AppIdentity.windowsCompanyName,
          guid: 'a1b2c3d4-e5f6-7a8b-9c0d-1e2f3a4b5c6d',
        );

    final InitializationSettings initSettings = InitializationSettings(
      android: androidSettings,
      iOS: darwinSettings,
      macOS: darwinSettings,
      linux: linuxSettings,
      windows: windowsSettings,
      web: const WebInitializationSettings(),
    );

    try {
      await _plugin.initialize(
        settings: initSettings,
        onDidReceiveNotificationResponse: (NotificationResponse response) {
          final action = response.actionId ?? 'complete';
          final id = response.id ?? 1;
          onActionReceived?.call(action, id);
        },
      );
      _initialized = true;
    } catch (e) {
      debugPrint('Notification service initialization notice: $e');
    }
  }

  Future<void> setLanguageCode(String languageCode) {
    return initialize(languageCode: languageCode, onAction: onActionReceived);
  }

  Future<bool> requestPermissions() async {
    try {
      bool? granted;
      final androidImplementation = _plugin
          .resolvePlatformSpecificImplementation<
            AndroidFlutterLocalNotificationsPlugin
          >();
      if (androidImplementation != null) {
        granted = await androidImplementation.requestNotificationsPermission();
        final exactAllowed = await androidImplementation
            .requestExactAlarmsPermission();
        return (granted ?? true) && (exactAllowed ?? true);
      }

      final iosImplementation = _plugin
          .resolvePlatformSpecificImplementation<
            IOSFlutterLocalNotificationsPlugin
          >();
      if (iosImplementation != null) {
        granted = await iosImplementation.requestPermissions(
          alert: true,
          badge: true,
          sound: true,
        );
        return granted ?? false;
      }

      final macosImplementation = _plugin
          .resolvePlatformSpecificImplementation<
            MacOSFlutterLocalNotificationsPlugin
          >();
      if (macosImplementation != null) {
        granted = await macosImplementation.requestPermissions(
          alert: true,
          badge: true,
          sound: true,
        );
        return granted ?? false;
      }

      // Linux and Windows use the operating system notification service and
      // don't expose a runtime permission prompt through this plugin.
      return _initialized;
    } catch (e) {
      debugPrint('Permission request notice: $e');
      return false;
    }
  }

  Future<void> scheduleStandupReminder({
    required int id,
    required DateTime scheduledTime,
    String? title,
    String? body,
  }) async {
    final french = _languageCode == 'fr';
    final effectiveTitle =
        title ?? (french ? 'C’est le moment de bouger !' : 'Time to stand up!');
    final effectiveBody =
        body ??
        (french
            ? 'Prenez 5 minutes pour vous étirer, respirer et bouger.'
            : 'Take a 5-minute break to stretch, breathe, and move.');

    final largeIcon = await _loadLargeIcon();

    final androidDetails = AndroidNotificationDetails(
      'standup_reminders_channel',
      french ? 'Rappels de mouvement' : 'Posture & Movement Reminders',
      channelDescription: french
          ? 'Rappels pour bouger et réduire la fatigue liée à la sédentarité'
          : 'Hourly reminders to move and prevent sedentary fatigue',
      importance: Importance.max,
      priority: Priority.high,
      icon: androidSmallIcon,
      largeIcon: largeIcon,
      playSound: true,
      actions: <AndroidNotificationAction>[
        AndroidNotificationAction(
          'complete',
          french ? 'Je me suis levé·e !' : 'I stood up!',
        ),
        AndroidNotificationAction(
          'snooze',
          french ? 'Prochain rappel' : 'Next reminder',
        ),
        AndroidNotificationAction('skip', french ? 'Passer' : 'Skip'),
      ],
    );

    const darwinDetails = DarwinNotificationDetails(
      presentAlert: true,
      presentSound: true,
      presentBadge: true,
      categoryIdentifier: 'standup_reminder',
    );

    final linuxDetails = LinuxNotificationDetails(
      actions: <LinuxNotificationAction>[
        LinuxNotificationAction(
          key: 'complete',
          label: french ? 'Je me suis levé·e !' : 'I stood up!',
        ),
        LinuxNotificationAction(
          key: 'snooze',
          label: french ? 'Prochain rappel' : 'Next reminder',
        ),
        LinuxNotificationAction(key: 'skip', label: french ? 'Passer' : 'Skip'),
      ],
    );

    final notificationDetails = NotificationDetails(
      android: androidDetails,
      iOS: darwinDetails,
      macOS: darwinDetails,
      linux: linuxDetails,
      windows: const WindowsNotificationDetails(),
    );

    try {
      if (defaultTargetPlatform == TargetPlatform.linux) {
        // The Linux desktop notification backend only supports immediate
        // notifications. Keep a foreground timer and emit at the due time.
        _linuxTimers.remove(id)?.cancel();
        final delay = scheduledTime.difference(DateTime.now());
        _linuxTimers[id] = Timer(delay.isNegative ? Duration.zero : delay, () {
          _linuxTimers.remove(id);
          _plugin.show(
            id: id,
            title: effectiveTitle,
            body: effectiveBody,
            notificationDetails: notificationDetails,
          );
        });
        return;
      }

      final tzTime = tz.TZDateTime.from(scheduledTime, tz.local);
      await _plugin.zonedSchedule(
        id: id,
        title: effectiveTitle,
        body: effectiveBody,
        scheduledDate: tzTime,
        notificationDetails: notificationDetails,
        androidScheduleMode: AndroidScheduleMode.exactAllowWhileIdle,
      );
    } catch (e) {
      debugPrint('Error scheduling notification: $e');
      // Fallback: show immediate notification if in foreground test
    }
  }

