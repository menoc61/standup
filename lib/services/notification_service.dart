  Future<void> cancelReminder(int id) async {
    _linuxTimers.remove(id)?.cancel();
    try {
      await _plugin.cancel(id: id);
    } catch (e) {
      debugPrint('Error canceling notification: $e');
    }
  }

  Future<void> cancelAll() async {
    for (final timer in _linuxTimers.values) {
      timer.cancel();
    }
    _linuxTimers.clear();
    try {
      await _plugin.cancelAll();
    } catch (e) {
      debugPrint('Error canceling all notifications: $e');
    }
  }

  void dispose() {
    for (final timer in _linuxTimers.values) {
      timer.cancel();
    }
    _linuxTimers.clear();
  }

  /// Keeps a rolling queue of OS-owned reminders. They can still be delivered
  /// while the app is suspended or closed; no periodic Dart worker is needed.
  /// The 48-item queue stays below iOS's pending local notification limit.
  ///
  /// [quietHours] is a `"HH:MM-HH:MM"` window during which no reminder is
  /// scheduled. The window may wrap past midnight (for example 22:00-06:00).
  ///
  /// [quiet] empties the queue outright. It is a runtime state rather than a
  /// schedule, so unlike [quietHours] it can only ever clear what is already
  /// posted — which is why the cancellation below happens before the early
  /// return rather than after it.
  ///
  /// [actionWindowMinutes] shifts each alert to the start of the actionable
  /// window rather than the cadence boundary, so the user is notified exactly
  /// when the stand action becomes valid.
  Future<void> scheduleReminderSeries({
    required DateTime firstReminder,
    required int frequencyMinutes,
    required String title,
    required String body,
    String? quietHours,
    bool quiet = false,
    int actionWindowMinutes = 0,
    int preludeMinutes = 0,
    String workDays = '1,2,3,4,5',
    int workStartMinute = 540,
    int workEndMinute = 1020,
    int dailyLimitMinutes = 0,
  }) {
    final operation = _queueOperations.then(
      (_) => _rebuildReminderSeries(
        firstReminder: firstReminder,
        frequencyMinutes: frequencyMinutes,
        title: title,
        body: body,
        quietHours: quietHours,
        quiet: quiet,
        actionWindowMinutes: actionWindowMinutes,
        preludeMinutes: preludeMinutes,
        workDays: workDays,
        workStartMinute: workStartMinute,
        workEndMinute: workEndMinute,
        dailyLimitMinutes: dailyLimitMinutes,
      ),
    );
    // A failed rebuild must be reported to its caller without poisoning the
    // queue: later preference changes still need a chance to repair it.
    _queueOperations = operation.catchError((Object error, StackTrace stack) {
      debugPrint('Unable to rebuild reminder queue: $error');
    });
    return operation;
  }

  Future<void> _rebuildReminderSeries({
    required DateTime firstReminder,
    required int frequencyMinutes,
    required String title,
    required String body,
    String? quietHours,
    bool quiet = false,
    int actionWindowMinutes = 0,
    int preludeMinutes = 0,
    String workDays = '1,2,3,4,5',
    int workStartMinute = 540,
    int workEndMinute = 1020,
    int dailyLimitMinutes = 0,
  }) async {
    if (frequencyMinutes <= 0) {
      throw ArgumentError.value(frequencyMinutes, 'frequencyMinutes');
    }
    final workSchedule = WorkSchedule(
      days: workDays.split(',').map(int.tryParse).whereType<int>(),
      startMinute: workStartMinute,
      endMinute: workEndMinute,
    );
    const firstId = AppCadence.reminderNotificationIdBase;
    const count = AppCadence.scheduledReminderQueueSize;
    for (var i = 0; i < count; i++) {
      await cancelReminder(firstId + i);
    }
    const preludeFirstId = AppCadence.preludeNotificationIdBase;
    for (var i = 0; i < count; i++) {
      await cancelReminder(preludeFirstId + i);
    }
    // Quiet mode is the whole job when it is on: the cancellations above have
    // just cleared both series, and re-posting anything would defeat the point.
    if (quiet) {
      debugPrint('Quiet mode: reminder queue emptied.');
      return;
    }

    // Refill 48 actual reminder slots across weekends, sparse custom schedules,
    // and quiet hours. Ninety days lets a one-day-per-week schedule stay queued.
    final reminders = reminderTimesForSchedule(
      firstBoundary: firstReminder,
      frequencyMinutes: frequencyMinutes,
      actionWindowMinutes: actionWindowMinutes,
      schedule: workSchedule,
      now: DateTime.now(),
      quietHours: quietHours,
      count: count,
      dailyLimitMinutes: dailyLimitMinutes,
    );
    if (reminders.isEmpty) {
      debugPrint(
        'Reminder queue is empty: no future action windows match the work '
        'schedule and quiet hours.',
      );
    }
    for (var i = 0; i < reminders.length; i++) {
      await scheduleStandupReminder(
        id: firstId + i,
        scheduledTime: reminders[i],
        title: title,
        body: body,
      );
    }

    // The prelude queue is desktop-only. Mobile spends its entire outstanding
    // request budget on the actionable reminders, and the in-app banner already
    // warns the foreground user on every platform.
    if (!_supportsPreludeQueue) return;

    final preludes = preludeTimesForReminders(
      reminders: reminders,
      preludeMinutes: preludeMinutes,
      now: DateTime.now(),
      schedule: workSchedule,
      quietHours: quietHours,
    );
    for (var i = 0; i < preludes.length; i++) {
      await schedulePreludeNotification(
        id: preludeFirstId + i,
        scheduledTime: preludes[i],
        title: _languageCode == 'fr'
            ? 'Pause dans $preludeMinutes min'
            : 'Break in $preludeMinutes min',
      );
    }
  }

  /// Whether this platform runs the prelude notification queue.
  ///
  /// Windows and Linux are the priority desktop platforms: the app must be
  /// running for either queue to fire, and on mobile the OS request budget is
  /// better spent on the reminders themselves.
  bool get _supportsPreludeQueue =>
      !kIsWeb &&
      (defaultTargetPlatform == TargetPlatform.windows ||
          defaultTargetPlatform == TargetPlatform.linux);

  Future<void> dispatchLaunchAction() async {
    try {
      final details = await _plugin.getNotificationAppLaunchDetails();
      final response = details?.notificationResponse;
      if (details?.didNotificationLaunchApp == true && response != null) {
        onActionReceived?.call(
          response.actionId ?? 'complete',
          response.id ?? 1,
        );
      }
    } catch (e) {
      debugPrint('Unable to read notification launch action: $e');
    }
  }
}
